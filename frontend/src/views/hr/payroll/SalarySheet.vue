<script setup>
import axios from 'axios';
import Swal from 'sweetalert2';
import { toast } from 'vue3-toastify';
import BasePagination from '@/components/common/BasePagination.vue';
import Breadcrumb from '@/components/common/Breadcrumb.vue';
import SearchSelect from '@/components/common/SearchSelect.vue';
import { usePaginatedFetch } from '@/composables/usePaginatedFetch';
import { usePermission } from '@/composables/usePermission';
import { usePrintable } from '@/composables/usePrintable';
import { useRoute } from 'vue-router';
import { SALARY_STATUSES, accountLabel, currentMonth, fetchPaymentAccounts, money, monthLabel, salaryStatusClass } from '../helpers';
import { t } from '@/i18n';

const route = useRoute();
const { can } = usePermission()
const { printTable } = usePrintable()

const {
    items,
    payload,
    loading,
    filters,
    pagination,
    fetchData,
    changePage,
    changePerPage,
} = usePaginatedFetch('/api/hr/salary-histories', {
    month: route.query.month || currentMonth(),
    department: '',
    status: '',
    payment_status: route.query.payment_status || '',
}, { perPage: 50 })

// Statuses a salary can be paid in, and those that can be ticked for a bulk action.
const PAYABLE = ['Approved', 'Partially Paid']
const SELECTABLE = ['Generated', ...PAYABLE]

const totals = computed(() => payload.value.totals ?? { count: 0, gross_salary: 0, total_deduction: 0, net_salary: 0, paid_amount: 0, due_amount: 0 })
const options = ref({ departments: [] })
const selected = ref([])
const detail = ref(null)
const detailOpen = ref(false)

watch(items, () => {
    selected.value = []
})

// No search button here: reload as soon as a filter changes.
// (Changing the page already triggers a fetch, so only fetch directly on page 1.)
watch(filters, () => {
    if (pagination.page !== 1) {
        pagination.page = 1
    } else {
        fetchData()
    }
})

const selectable = computed(() => items.value.filter((i) => SELECTABLE.includes(i.status)).map((i) => i.id))
const allSelected = computed(() => selectable.value.length > 0 && selected.value.length === selectable.value.length)
const toggleAll = (checked) => {
    selected.value = checked ? [...selectable.value] : []
}
const selectedWith = (statuses) => items.value.filter((i) => selected.value.includes(i.id) && statuses.includes(i.status)).map((i) => i.id)

const changeStatus = async (action, fromStatus) => {
    const ids = selectedWith([fromStatus])
    const confirm = await Swal.fire({
        title: t('Approve {count} salaries?', { count: ids.length }),
        text: t('Approved salaries can no longer be recalculated.'),
        icon: 'question',
        showCancelButton: true,
        confirmButtonText: t('Yes, approve'),
    })
    if (!confirm.isConfirmed) return

    try {
        const { data } = await axios.post(`/api/hr/salary-histories/${action}`, { ids })
        toast.success(data.message)
        fetchData()
    } catch (e) {
        toast.error(e.response?.data?.message || t('Failed to update salaries.'))
    }
}

// Each payment posts to the ledger, so it needs the cash/bank account and date.
// `paySalary` is the one salary being paid (any amount up to its due), or null
// to pay the whole due of every selected salary.
const payOpen = ref(false)
const isPaying = ref(false)
const paymentAccounts = ref([])
const paySalary = ref(null)
const payForm = reactive({ amount: '', payment_account_id: '', payment_date: new Date().toISOString().slice(0, 10), remarks: '' })
const payErrors = reactive({})

const selectedDueTotal = computed(() => items.value
    .filter((i) => selectedWith(PAYABLE).includes(i.id))
    .reduce((sum, i) => sum + Number(i.due_amount || 0), 0))

const openPayDialog = async (salary) => {
    for (const key in payErrors) delete payErrors[key]
    paySalary.value = salary
    payForm.amount = salary ? salary.due_amount : ''
    payForm.remarks = ''
    payOpen.value = true
    if (!paymentAccounts.value.length) {
        try {
            paymentAccounts.value = await fetchPaymentAccounts()
        } catch (e) {
            toast.error(e.response?.data?.message || t('Failed to load accounts.'))
        }
    }
}

const pay = async () => {
    for (const key in payErrors) delete payErrors[key]
    isPaying.value = true

    const { amount, remarks, ...account } = payForm

    try {
        const { data } = paySalary.value
            ? await axios.post(`/api/hr/salary-histories/${paySalary.value.id}/payments`, { ...account, amount, remarks })
            : await axios.post('/api/hr/salary-histories/pay', { ...account, ids: selectedWith(PAYABLE) })
        toast.success(data.message)
        payOpen.value = false
        fetchData()
    } catch (e) {
        if (e.response?.status === 422) {
            const respErrors = e.response.data.data
            for (const key in respErrors) payErrors[key] = respErrors[key].join(' ')
        } else {
            toast.error(e.response?.data?.message || t('Failed to update salaries.'))
        }
    } finally {
        isPaying.value = false
    }
}

const cancel = async (item) => {
    const { value: reason, isConfirmed } = await Swal.fire({
        title: t('Cancel salary of {name}?', { name: item.employee_name }),
        text: t('The record is kept for audit and the month can be generated again for this employee.'),
        input: 'text',
        inputPlaceholder: t('Reason for cancelling'),
        inputValidator: (value) => (!value ? t('A reason is required.') : undefined),
        icon: 'warning',
        showCancelButton: true,
        confirmButtonText: t('Cancel salary'),
        cancelButtonText: t('Keep'),
    })
    if (!isConfirmed) return

    try {
        const { data } = await axios.post(`/api/hr/salary-histories/${item.id}/cancel`, { reason })
        toast.success(data.message)
        fetchData()
    } catch (e) {
        const errors = e.response?.data?.data
        toast.error(errors ? Object.values(errors).flat().join(' ') : (e.response?.data?.message || t('Failed to cancel.')))
    }
}

// The list row opens at once; the payments come with the full record.
const showDetail = async (item) => {
    detail.value = item
    detailOpen.value = true
    try {
        const { data } = await axios.get(`/api/hr/salary-histories/${item.id}`)
        if (detailOpen.value && detail.value?.id === item.id) detail.value = data.data
    } catch (e) {
        console.error(e)
    }
}

const deletePayment = async (payment) => {
    const result = await Swal.fire({
        title: t('Delete this salary payment?'),
        text: t('Its ledger entry is removed and the amount becomes due again.'),
        icon: 'warning',
        showCancelButton: true,
        confirmButtonText: t('Yes, delete'),
    })
    if (!result.isConfirmed) return

    try {
        const { data } = await axios.delete(`/api/hr/salary-payments/${payment.id}`)
        toast.success(data.message)
        detail.value = data.data
        fetchData()
    } catch (e) {
        toast.error(e.response?.data?.message || t('Failed to delete.'))
    }
}

const print = async () => {
    const { data } = await axios.get('/api/hr/salary-histories', { params: { ...filters, per_page: 100000 } })
    printTable({
        title: t('Salary Sheet - {month}', { month: monthLabel(filters.month) || t('All months') }),
        items: data.data?.salaries ?? [],
        columns: [
            { key: 'index', label: '#' },
            { key: 'employee_code', label: t('ID') },
            { key: 'employee_name', label: t('Name') },
            { key: 'designation', label: t('Designation') },
            { key: 'basic_salary', label: t('Basic'), align: 'right', format: money },
            { key: 'total_allowance', label: t('Allowances'), align: 'right', format: money },
            { key: 'overtime_amount', label: t('Overtime'), align: 'right', format: money },
            { key: 'gross_salary', label: t('Gross'), align: 'right', format: money },
            { key: 'total_deduction', label: t('Deduction'), align: 'right', format: money },
            { key: 'net_salary', label: t('Net'), align: 'right', format: money },
