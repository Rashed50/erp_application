<template lang="html">
    <Breadcrumb title="Salary Sheet" buttonText="Generate Salary" :buttonLink="{ name: 'admin_hr_payroll_generate' }"
        buttonIcon="fa-solid fa-calculator" />

    <div class="main-content-wrapper mt-4">
        <div class="container-fluid">
            <v-card style="padding: 5px; margin-top: 15px;">
                <div class="row align-items-center mb-2">
                    <div class="col-md-2">
                        <input type="month" class="form-control" v-model="filters.month" />
                    </div>
                    <div class="col-md-2">
                        <SearchSelect v-model="filters.department" :items="options.departments" item-value="name"
                            :placeholder="$t('All Departments')" />
                    </div>
                    <div class="col-md-2">
                        <SearchSelect v-model="filters.status" :items="SALARY_STATUSES" :item-title="(s) => $t(s)"
                            :item-value="(s) => s" :placeholder="$t('All (except cancelled)')" />
                    </div>
                    <div class="col-md-2">
                        <select class="form-select" v-model="filters.payment_status">
                            <option value="">{{ $t('Paid & Unpaid') }}</option>
                            <option value="paid">{{ $t('Paid') }}</option>
                            <option value="unpaid">{{ $t('Unpaid / Due') }}</option>
                        </select>
                    </div>
                    <div class="col-md-4 d-flex justify-content-end gap-2">
                        <v-btn v-if="can(['payroll.approve'])" class="text-none text-white" color="blue-darken-3"
                            rounded="0" variant="flat" :disabled="!selectedWith(['Generated']).length"
                            @click="changeStatus('approve', 'Generated')">
                            {{ $t('Approve') }} ({{ selectedWith(['Generated']).length }})
                        </v-btn>
                        <v-btn v-if="can(['payroll.pay'])" class="text-none text-white" color="green-darken-2" rounded="0"
                            variant="flat" :disabled="!selectedWith(PAYABLE).length"
                            @click="openPayDialog(null)">
                            {{ $t('Mark Paid') }} ({{ selectedWith(PAYABLE).length }})
                        </v-btn>
                        <v-btn class="text-none" color="grey-lighten-3" rounded="0" variant="flat" @click="print">
                            <i class="fa-solid fa-print me-1"></i> {{ $t('Print') }}
                        </v-btn>
                    </div>
                </div>

                <div class="table-responsive">
                    <v-table class="custom-bordered" density="compact">
                        <thead>
                            <tr>
                                <th class="text-center">
                                    <input type="checkbox" class="form-check-input" :checked="allSelected"
                                        @change="toggleAll($event.target.checked)" />
                                </th>
                                <th>{{ $t('Month') }}</th>
                                <th>{{ $t('Employee') }}</th>
                                <th class="text-right">{{ $t('Basic') }}</th>
                                <th class="text-right">{{ $t('Allowances') }}</th>
                                <th class="text-right">{{ $t('OT + Bonus') }}</th>
                                <th class="text-right">{{ $t('Gross') }}</th>
                                <th class="text-right">{{ $t('Deduction') }}</th>
                                <th class="text-right">{{ $t('Net') }}</th>
                                <th class="text-right">{{ $t('Paid') }}</th>
                                <th class="text-right">{{ $t('Due') }}</th>
                                <th class="text-center">{{ $t('Status') }}</th>
                                <th>{{ $t('Generated By') }}</th>
                                <th>{{ $t('Approved By') }}</th>
                                <th class="text-center">{{ $t('Action') }}</th>
                            </tr>
                        </thead>
                        <tbody>
                            <tr v-if="loading">
                                <td colspan="15" class="text-center py-4">
                                    <v-progress-linear indeterminate color="primary"></v-progress-linear>
                                </td>
                            </tr>
                            <tr v-else-if="!items.length">
                                <td colspan="15" class="text-center py-4">{{ $t('No salaries found.') }}</td>
                            </tr>
                            <tr v-else v-for="item in items" :key="item.id">
                                <td class="text-center">
                                    <input type="checkbox" class="form-check-input" :value="item.id" v-model="selected"
                                        :disabled="!SELECTABLE.includes(item.status)" />
                                </td>
                                <td>{{ monthLabel(item.salary_month) }}</td>
                                <td>
                                    {{ item.employee_code }} - {{ item.employee_name }}
                                    <div class="small text-muted">{{ item.designation }} · {{ item.department }}</div>
                                </td>
                                <td class="text-right">{{ money(item.basic_salary) }}</td>
                                <td class="text-right">{{ money(item.total_allowance) }}</td>
                                <td class="text-right">{{ money(item.overtime_amount + item.bonus + item.other_addition) }}</td>
                                <td class="text-right">{{ money(item.gross_salary) }}</td>
                                <td class="text-right">{{ money(item.total_deduction) }}</td>
                                <td class="text-right"><strong>{{ money(item.net_salary) }}</strong></td>
                                <td class="text-right text-success">{{ money(item.paid_amount) }}</td>
                                <td class="text-right" :class="{ 'text-danger': item.due_amount > 0 && item.status !== 'Generated' }">
                                    {{ money(item.due_amount) }}
                                </td>
                                <td class="text-center">
                                    <span :class="salaryStatusClass(item.status)" :title="item.cancel_reason || ''">
                                        {{ $t(item.status) }}
                                    </span>
                                </td>
                                <td>{{ item.generated_by_name || '-' }}</td>
                                <td>{{ item.approved_by_name || '-' }}</td>
                                <td class="text-center">
                                    <v-btn size="small" variant="text" color="blue-darken-3" @click="showDetail(item)">
                                        {{ $t('View') }}
                                    </v-btn>
                                    <v-btn v-if="can(['payroll.pay']) && PAYABLE.includes(item.status)" size="small"
                                        variant="text" color="green-darken-2" @click="openPayDialog(item)">
                                        {{ $t('Pay') }}
                                    </v-btn>
                                    <v-btn v-if="can(['payroll.cancel']) && ['Generated', 'Approved'].includes(item.status)"
                                        size="small" variant="text" color="red-darken-2" @click="cancel(item)">
                                        {{ $t('Cancel') }}
                                    </v-btn>
                                </td>
                            </tr>
                        </tbody>
                        <tfoot v-if="items.length">
                            <tr class="fw-bold">
                                <td colspan="6" class="text-right">{{ $t('Total ({count} salaries, all pages)', { count: totals.count }) }}</td>
                                <td class="text-right">{{ money(totals.gross_salary) }}</td>
                                <td class="text-right">{{ money(totals.total_deduction) }}</td>
                                <td class="text-right">{{ money(totals.net_salary) }}</td>
                                <td class="text-right text-success">{{ money(totals.paid_amount) }}</td>
                                <td class="text-right text-danger">{{ money(totals.due_amount) }}</td>
                                <td colspan="4"></td>
                            </tr>
                        </tfoot>
                    </v-table>
                </div>

                <BasePagination :current-page="pagination.page" :per-page="pagination.perPage" :total="pagination.total"
                    :last-page="pagination.lastPage" @page-change="changePage" @per-page-change="changePerPage" />
            </v-card>
        </div>
    </div>

    <!-- Pay one salary (all or part of its due) or the full due of the selected salaries -->
    <v-dialog v-model="payOpen" max-width="520">
        <v-card>
            <v-card-title v-if="paySalary">
                {{ $t('Pay salary of {name}', { name: paySalary.employee_name }) }} · {{ monthLabel(paySalary.salary_month) }}
            </v-card-title>
            <v-card-title v-else>{{ $t('Mark {count} salaries as paid?', { count: selectedWith(PAYABLE).length }) }}</v-card-title>
            <v-card-text>
                <p class="text-muted small">
                    {{ $t('The payment is made from the account below and posted to the ledger. A salary with payments can no longer be cancelled.') }}
                </p>
                <div class="alert alert-light border d-flex justify-content-between">
                    <span>{{ $t('Due salary') }}</span><strong>{{ money(paySalary ? paySalary.due_amount : selectedDueTotal) }}</strong>
                </div>
                <div class="form-group mb-3" v-if="paySalary">
                    <label>{{ $t('Amount:') }} <span class="text-danger">*</span></label>
                    <input type="number" step="0.01" min="0.01" :max="paySalary.due_amount" class="form-control"
                        v-model.number="payForm.amount" required />
                    <small class="text-muted">{{ $t('Enter less than the due amount to pay part of the salary.') }}</small>
                    <div v-if="payErrors.amount" class="error-msg">{{ payErrors.amount }}</div>
                </div>
                <div class="form-group mb-3">
                    <label>{{ $t('Paid From:') }} <span class="text-danger">*</span></label>
                    <select class="form-control" v-model="payForm.payment_account_id" required>
                        <option value="" disabled>{{ $t('Select account') }}</option>
                        <option v-for="account in paymentAccounts" :key="account.id" :value="account.id">
                            {{ accountLabel(account) }}
                        </option>
                    </select>
                    <div v-if="payErrors.payment_account_id" class="error-msg">{{ payErrors.payment_account_id }}</div>
                </div>
                <div class="form-group mb-3">
                    <label>{{ $t('Payment Date:') }} <span class="text-danger">*</span></label>
                    <input type="date" class="form-control" v-model="payForm.payment_date" required />
                    <div v-if="payErrors.payment_date" class="error-msg">{{ payErrors.payment_date }}</div>
                </div>
                <div class="form-group" v-if="paySalary">
                    <label>{{ $t('Remarks:') }}</label>
                    <input type="text" class="form-control" v-model="payForm.remarks" maxlength="255" />
                </div>
                <div v-if="payErrors.status" class="error-msg">{{ payErrors.status }}</div>
            </v-card-text>
            <v-card-actions>
                <v-spacer></v-spacer>
                <v-btn class="text-none" color="grey-lighten-3" rounded="0" variant="flat" @click="payOpen = false">
                    {{ $t('Cancel') }}
                </v-btn>
                <v-btn class="text-none text-white" color="green-darken-2" rounded="0" variant="flat"
                    :disabled="isPaying || !payForm.payment_account_id" :loading="isPaying" @click="pay">
                    {{ $t(paySalary ? 'Pay' : 'Yes, mark as paid') }}
                </v-btn>
            </v-card-actions>
        </v-card>
    </v-dialog>

    <!-- Salary breakdown -->
    <v-dialog v-model="detailOpen" max-width="640">
        <v-card v-if="detail">
            <v-card-title>
                {{ detail.employee_code }} - {{ detail.employee_name }} · {{ monthLabel(detail.salary_month) }}
            </v-card-title>
            <v-card-text>
                <div class="row">
                    <div class="col-6">
                        <h6>{{ $t('Earnings') }}</h6>
                        <table class="table table-sm">
                            <tbody>
                                <tr>
                                    <td>{{ $t('Basic') }} ({{ Number(detail.present_days) + Number(detail.paid_leave_days) }} {{ $t('days') }} × {{ money(detail.per_day_rate) }})</td>
                                    <td class="text-end">{{ money(detail.basic_salary) }}</td>
                                </tr>
                                <tr><td>{{ $t('House Rent') }}</td><td class="text-end">{{ money(detail.house_rent) }}</td></tr>
                                <tr><td>{{ $t('Medical') }}</td><td class="text-end">{{ money(detail.medical_allowance) }}</td></tr>
                                <tr><td>{{ $t('Transport') }}</td><td class="text-end">{{ money(detail.transport_allowance) }}</td></tr>
                                <tr><td>{{ $t('Food') }}</td><td class="text-end">{{ money(detail.food_allowance) }}</td></tr>
                                <tr><td>{{ $t('Other Allowance') }}</td><td class="text-end">{{ money(detail.other_allowance) }}</td></tr>
                                <tr>
                                    <td>{{ $t('Overtime') }} ({{ detail.overtime_hours }}h × {{ money(detail.overtime_rate) }})</td>
                                    <td class="text-end">{{ money(detail.overtime_amount) }}</td>
                                </tr>
                                <tr><td>{{ $t('Bonus') }}</td><td class="text-end">{{ money(detail.bonus) }}</td></tr>
                                <tr><td>{{ $t('Other Addition') }}</td><td class="text-end">{{ money(detail.other_addition) }}</td></tr>
                                <tr class="fw-bold"><td>{{ $t('Gross') }}</td><td class="text-end">{{ money(detail.gross_salary) }}</td></tr>
                            </tbody>
                        </table>
                    </div>
                    <div class="col-6">
                        <h6>{{ $t('Deductions') }}</h6>
                        <table class="table table-sm">
                            <tbody>
                                <!-- Only salaries generated before per-day pay deducted absence. -->
                                <tr v-if="Number(detail.absence_deduction)">
                                    <td>{{ $t('Absence') }} ({{ detail.absent_days }} × {{ money(detail.per_day_rate) }})</td>
                                    <td class="text-end">{{ money(detail.absence_deduction) }}</td>
                                </tr>
                                <tr v-if="Number(detail.unpaid_leave_deduction)">
                                    <td>{{ $t('Unpaid Leave') }} ({{ detail.unpaid_leave_days }} × {{ money(detail.per_day_rate) }})</td>
                                    <td class="text-end">{{ money(detail.unpaid_leave_deduction) }}</td>
                                </tr>
                                <tr><td>{{ $t('Other Deductions') }}</td><td class="text-end">{{ money(detail.other_deduction) }}</td></tr>
                                <tr><td>{{ $t('Advance Salary Installment') }}</td><td class="text-end">{{ money(detail.advance_deduction) }}</td></tr>
                                <tr class="fw-bold"><td>{{ $t('Total') }}</td><td class="text-end">{{ money(detail.total_deduction) }}</td></tr>
                            </tbody>
                        </table>
                        <h6>{{ $t('Attendance') }}</h6>
                        <div class="small">
                            {{ $t('Employed {employed}/{total} days', { employed: detail.employed_days, total: detail.days_in_month }) }} ·
                            {{ $t('Working') }} {{ detail.working_days }} · {{ $t('Present') }} {{ detail.present_days }} ·
                            {{ $t('Paid leave') }} {{ detail.paid_leave_days }}
                        </div>
                        <div class="small text-muted mt-1">{{ $t('Day rate based on') }} {{ $t(detail.deduction_basis === 'gross' ? 'basic + allowances' : 'basic') }}</div>
                    </div>
                </div>
                <div class="alert alert-success mb-0 d-flex justify-content-between">
                    <strong>{{ $t('Net Salary') }}</strong><strong>{{ money(detail.net_salary) }}</strong>
                </div>
                <div class="d-flex justify-content-between small mt-2 px-1">
                    <span>{{ $t('Paid') }}: <strong class="text-success">{{ money(detail.paid_amount) }}</strong></span>
                    <span>{{ $t('Due') }}: <strong class="text-danger">{{ money(detail.due_amount) }}</strong></span>
                </div>
                <template v-if="detail.payments?.length">
                    <h6 class="mt-3">{{ $t('Payments') }}</h6>
                    <table class="table table-sm mb-0">
                        <thead>
                            <tr>
                                <th>{{ $t('Date') }}</th>
                                <th>{{ $t('Paid From') }}</th>
                                <th class="text-end">{{ $t('Amount') }}</th>
                                <th>{{ $t('Remarks') }}</th>
                                <th>{{ $t('Entry By') }}</th>
                                <th></th>
                            </tr>
                        </thead>
                        <tbody>
                            <tr v-for="payment in detail.payments" :key="payment.id">
                                <td>{{ payment.payment_date }}</td>
                                <td>{{ payment.payment_account_name }}</td>
                                <td class="text-end">{{ money(payment.amount) }}</td>
                                <td>{{ payment.remarks }}</td>
                                <td>{{ payment.created_by_name }}</td>
                                <td class="text-end">
                                    <v-btn v-if="can(['payroll.pay'])" size="small" color="red-darken-2" variant="text"
                                        icon="mdi-delete" @click="deletePayment(payment)"></v-btn>
                                </td>
                            </tr>
                        </tbody>
                    </table>
                </template>
                <div class="small text-muted mt-2" v-if="detail.cancel_reason">{{ $t('Cancelled:') }} {{ detail.cancel_reason }}</div>
            </v-card-text>
            <v-card-actions>
                <v-spacer></v-spacer>
                <v-btn class="text-none" color="grey-lighten-3" rounded="0" variant="flat" @click="detailOpen = false">
                    {{ $t('Close') }}
                </v-btn>
            </v-card-actions>
        </v-card>
    </v-dialog>
